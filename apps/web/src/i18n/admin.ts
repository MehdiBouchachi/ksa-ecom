export type AdminDict = Dict;
export const adminDict = (l: "ar" | "en"): AdminDict => (l === "en" ? en : ar);

export function statusLabels(l: "ar" | "en") {
  const src = l === "en" ? enLabels : arLabels;
  return {
    order: src.orderStatusLabel as Record<OrderStatus, string>,
    payment: src.paymentStatusLabel as Record<PaymentStatus, string>,
    shipping: src.shipmentStatusLabel as Record<ShipmentStatus, string>,
    prefix: l === "en" ? { order: "Order", payment: "Payment", shipping: "Shipping" } : { order: "الطلب", payment: "الدفع", shipping: "الشحن" },
  };
}
